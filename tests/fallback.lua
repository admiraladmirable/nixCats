-- Run with nvim -u NONE: validate fallback without downloading plugins.
vim.opt.runtimepath:prepend(assert(vim.env.EDITOR_CONFIG_SOURCE))
assert(vim.g.nix_info_plugin_name == nil)
local utils = require('nixCatsUtils')
assert(not utils.isNixCats)
utils.setup({ non_nix_value = true })
assert(nixCats('general.extra') == true)
assert(utils.enableForCategory('debug', false) == false)
assert(utils.getCatOrDefault('colorscheme', 'fallback') == 'fallback')
assert(utils.lazyAdd('download', 'packaged') == 'download')
assert(nixCats.extra('nixdExtras.nixpkgs') == nil)
assert(nixCats.pawsible({ 'allPlugins', 'opt', 'nvim-lspconfig' }) == nil)
utils.setup({ non_nix_value = false })
assert(nixCats('general.extra') == false)
print('Non-Nix adapter fallback passed')
vim.cmd('qa!')
